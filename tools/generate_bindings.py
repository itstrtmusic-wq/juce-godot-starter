#!/usr/bin/env python3
"""Generate Godot registrations and a coverage reference from the explicit binding manifest.

This generates the declared wrappers, not arbitrary C++/JUCE bindings. Each class
still needs an implementation in src/juce_api.* or src/juce_dsp_network.*.
"""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
spec = json.loads((root / 'bindings/api.json').read_text(encoding='utf-8'))
classes = spec['classes']
lines = ['// Generated by tools/generate_bindings.py. Do not edit.',
         '#include "juce_api.h"', '#include "juce_dsp_network.h"',
         '#include <godot_cpp/classes/json.hpp>', 'using namespace godot;', '']
for cls in classes:
    name = cls['name']
    lines.append(f'void {name}::_bind_methods() {{')
    for m in cls['methods']:
        args = ', '.join(json.dumps(s) for s in [m['name']] + m['args'])
        defaults = ''.join(', DEFVAL(' + d + ')' for d in m['defaults'])
        if m['static']:
            lines.append(f'    ClassDB::bind_static_method("{name}", D_METHOD({args}), &{name}::{m["name"]}{defaults});')
        else:
            lines.append(f'    ClassDB::bind_method(D_METHOD({args}), &{name}::{m["name"]}{defaults});')
    lines.append('}\n')
manifest = json.dumps(spec, separators=(',', ':'))
lines += ['Dictionary JUCE::get_api_manifest() {',
          f'    return JSON::parse_string(String::utf8(R"JUCE_MANIFEST({manifest})JUCE_MANIFEST"));', '}',
          'PackedStringArray JUCE::get_supported_classes() {', '    PackedStringArray result;']
lines += [f'    result.append("{c["name"]}");' for c in classes]
lines += ['    return result;', '}', '', 'void register_juce_api() {']
lines += [f'    ClassDB::register_class<{c["name"]}>();' for c in classes]
lines += ['}', '']
reference = ['# GDScript binding reference', '',
             f'API version: **{spec["version"]}**. {len(classes)} classes and {sum(len(c["methods"]) for c in classes)} methods are declared below.', '',
             'Generated from `bindings/api.json`. These are explicit supported bindings, not a complete JUCE wrapper. Use `JUCE.get_api_manifest()` to inspect this surface at runtime.', '',
             'All objects are owned Godot reference-counted objects. Factories can return null on invalid input; processing/configuration methods generally return a success boolean. Audio, MIDI and file data are copied when crossing ownership boundaries. ClassDB also exposes native return and argument types in the editor.', '',
             'See [DSP networks](DSP_NETWORKS.md) for graph topology, node parameters, automation and live-input setup. See [examples](../demo/examples) for executable GDScript.', '']
for cls in classes:
    reference += [f'## {cls["name"]}', '', cls['description'], '', f'JUCE implementation: `{cls["juce"]}`.', '', '| Method | Defaults for trailing arguments |', '| --- | --- |']
    for m in cls['methods']:
        method = ('static ' if m['static'] else '') + m['name'] + '(' + ', '.join(m['args']) + ')'
        defaults = ', '.join(m['defaults']) or '—'
        reference += [f'| `{method}` | `{defaults}` |']
    reference += ['']
outputs = {root/'src/generated_bindings.cpp': '\n'.join(lines), root/'docs/API_REFERENCE.md': '\n'.join(reference)}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for path, data in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != data:
            raise SystemExit(f'Stale generated file: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data, encoding='utf-8', newline='\n')
print(f'{len(classes)} classes, {sum(len(c["methods"]) for c in classes)} methods: generated bindings ' + ('are current' if args.check else 'updated'))

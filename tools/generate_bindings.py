#!/usr/bin/env python3
"""Generate Godot registrations and a coverage reference from the explicit binding manifest.

This generates the declared wrappers, not arbitrary C++/JUCE bindings. Handwritten adapters and reviewed processor metadata define the native surface;
this tool does not infer safe ownership or threading from arbitrary JUCE headers.
"""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
spec = json.loads((root / 'bindings/api.json').read_text(encoding='utf-8'))
classes = spec['classes']
lines = ['// Generated by tools/generate_bindings.py. Do not edit.',
         '#include "juce_api.h"', '#include "juce_dsp_network.h"', '#include "generated_effects.h"',
         '#include <godot_cpp/classes/json.hpp>', 'using namespace godot;', '']
for cls in classes:
    name = cls['name']
    lines.append(f'void {name}::_bind_methods() {{')
    for m in cls['methods']:
        args = ', '.join(json.dumps(s) for s in [m['name']] + m['args'])
        defaults = ''.join(', DEFVAL(' + d + ')' for d in m['defaults'])
        if m['static']:
            lines.append(f'    ClassDB::bind_static_method("{name}", D_METHOD({args}), &{name}::{m["name"]}{defaults});')
        else:
            lines.append(f'    ClassDB::bind_method(D_METHOD({args}), &{name}::{m["name"]}{defaults});')
    lines.append('}\n')
manifest = json.dumps(spec, separators=(',', ':'))
# Keep each native string literal below MSVC's per-literal size limit as the API grows.
lines += ['Dictionary JUCE::get_api_manifest() {', '    String text;']
for offset in range(0, len(manifest), 6000):
    lines.append('    text += String::utf8(R"JUCE_MANIFEST(' + manifest[offset:offset+6000] + ')JUCE_MANIFEST");')
lines += ['    return JSON::parse_string(text);', '}',
          'PackedStringArray JUCE::get_supported_classes() {', '    PackedStringArray result;']
lines += [f'    result.append("{c["name"]}");' for c in classes]
lines += ['    return result;', '}', '', 'void register_juce_api() {']
lines += [f'    ClassDB::register_class<{c["name"]}>();' for c in classes]
lines += ['}', '']
reference = ['# GDScript binding reference', '',
             f'API version: **{spec["version"]}**. {len(classes)} classes and {sum(len(c["methods"]) for c in classes)} methods are declared below.', '',
             'Generated from `bindings/api.json`. These are explicit supported bindings, not a complete JUCE wrapper. Use `JUCE.get_api_manifest()` to inspect this surface at runtime.', '',
             'All objects are owned Godot reference-counted objects. Factories can return null on invalid input; processing/configuration methods generally return a success boolean. Audio, MIDI and file data are copied when crossing ownership boundaries. ClassDB also exposes native return and argument types in the editor.', '',
             'See [DSP networks](DSP_NETWORKS.md) for graph topology, node parameters, automation and live-input setup. See [examples](../demo/examples) for executable GDScript.', '']
for cls in classes:
    reference += [f'## {cls["name"]}', '', cls['description'], '', f'JUCE implementation: `{cls["juce"]}`.', '', '| Method | Defaults for trailing arguments |', '| --- | --- |']
    for m in cls['methods']:
        method = ('static ' if m['static'] else '') + m['name'] + '(' + ', '.join(m['args']) + ')'
        defaults = ', '.join(m['defaults']) or '—'
        reference += [f'| `{method}` | `{defaults}` |']
    if 'effect' in cls:
        reference += ['', '| Parameter | Default | Min | Max |', '| --- | --- | --- | --- |']
        for p in cls['effect']['parameters']:
            reference += [f'| `{p["name"]}` | {p["default"]} | {p["min"]} | {p["max"]} |']
    reference += ['']
# Generate the uniform ownership/validation adapters for explicitly described DSP classes.
effect_header = ['// Generated by tools/generate_bindings.py. Do not edit.', '#pragma once', '#include "prepared_effect.h"', 'namespace godot {']
effect_source = ['// Generated by tools/generate_bindings.py. Do not edit.', '#include "generated_effects.h"', 'namespace godot {']
for cls in classes:
    if 'effect' not in cls:
        continue
    name = cls['name']
    effect = cls['effect']
    params = effect['parameters']
    effect_header += [f'class {name} : public RefCounted {{', f'    GDCLASS({name}, RefCounted)', f'    PreparedEffect<{effect["processor"]}> state;']
    for p in params:
        effect_header += [f'    float p_{p["name"]} = {float(p["default"])}f;']
    effect_header += ['    void apply_settings();', 'protected: static void _bind_methods();', 'public:',
        '    bool prepare(double sample_rate, int max_block_size = 512, int channels = 2) { if (!state.prepare(sample_rate, max_block_size, channels)) return false; apply_settings(); return true; }',
        '    bool set_parameters(const Dictionary& parameters);', '    Dictionary get_parameters() const;', '    Dictionary get_parameter_info() const;',
        '    bool reset() { return state.reset(); }', '    bool process(const Ref<JuceAudioBuffer>& buffer) { return state.process(buffer); }',
        '    String get_last_error() const { return state.error; }', '};']
    effect_source += [f'void {name}::apply_settings() {{']
    for p in params:
        value = 'p_' + p['name']
        if p.get('nyquist'):
            value = f'std::min({value}, float(state.sample_rate * 0.45))'
        effect_source += [f'    state.processor.{p["setter"]}({value});']
    effect_source += ['}', f'bool {name}::set_parameters(const Dictionary& parameters) {{']
    for p in params:
        effect_source += [f'    float next_{p["name"]} = p_{p["name"]};']
    effect_source += ['    for (const Variant& raw_key : parameters.keys()) {',
        '        if (raw_key.get_type() != Variant::STRING && raw_key.get_type() != Variant::STRING_NAME) return state.fail("Parameter keys must be strings");',
        '        const String key = raw_key;', '        const Variant value = parameters[raw_key];',
        '        if (value.get_type() != Variant::FLOAT && value.get_type() != Variant::INT) return state.fail("Parameter values must be numbers");',
        '        const double number = value;', '        if (!std::isfinite(number)) return state.fail("Parameter values must be finite");']
    for index, p in enumerate(params):
        keyword = 'if' if index == 0 else 'else if'
        effect_source += [f'        {keyword} (key == "{p["name"]}") {{ if (number < float({float(p["min"])}) || number > float({float(p["max"])})) return state.fail("Parameter is out of range: {p["name"]}"); next_{p["name"]} = float(number); }}']
    effect_source += ['        else return state.fail("Unknown parameter: " + key);', '    }']
    for p in params:
        effect_source += [f'    p_{p["name"]} = next_{p["name"]};']
    effect_source += ['    if (state.prepared) apply_settings();', '    state.error = ""; return true;', '}', f'Dictionary {name}::get_parameters() const {{', '    Dictionary result;']
    for p in params:
        effect_source += [f'    result["{p["name"]}"] = p_{p["name"]};']
    effect_source += ['    return result;', '}', f'Dictionary {name}::get_parameter_info() const {{', '    Dictionary result;']
    for p in params:
        effect_source += [f'    {{ Dictionary info; info["min"] = {float(p["min"])}; info["max"] = {float(p["max"])}; info["default"] = {float(p["default"])}; result["{p["name"]}"] = info; }}']
    effect_source += ['    return result;', '}']
effect_header += ['}', '']
effect_source += ['}', '']
outputs = {root/'src/generated_bindings.cpp': '\n'.join(lines), root/'docs/API_REFERENCE.md': '\n'.join(reference), root/'src/generated_effects.h': '\n'.join(effect_header), root/'src/generated_effects.cpp': '\n'.join(effect_source)}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for path, data in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != data:
            raise SystemExit(f'Stale generated file: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data, encoding='utf-8', newline='\n')
print(f'{len(classes)} classes, {sum(len(c["methods"]) for c in classes)} methods: generated bindings ' + ('are current' if args.check else 'updated'))
